def export_glb(path, roots):
    """Export the given root objects (and their children) to one .glb file."""
    for ob in bpy.context.scene.objects:
        ob.select_set(False)
    for r in roots:
        for d in descendants(r):
            d.select_set(True)
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format='GLB',
        use_selection=True,
        export_yup=True,
        export_apply=True,
        export_texcoords=False,
        export_normals=True,
        export_vertex_color='ACTIVE',
        export_all_vertex_colors=False,
        export_materials='EXPORT',
        export_extras=True,
        export_animations=False,
        export_cameras=False,
        export_lights=False,
    )


def stats(roots):
    """Return {root_name: triangle_count} for a quick budget check."""
    out = {}
    for r in roots:
        tris = 0
        for d in descendants(r):
            if d.type == 'MESH':
                for p in d.data.polygons:
                    tris += len(p.vertices) - 2
        out[r.name] = tris
    return out
