"""
ghlib — tiny procedural-modeling toolkit for Gloamhollow's Blender assets.

Every model in the game is generated by Python scripts that run inside
Blender (or the `bpy` module).  This file holds the shared helpers so all
assets share one look: chunky low-poly shapes, slightly jittered vertices,
per-face colour variation, fake baked AO and a muted, dark palette.

Conventions
-----------
* Units are metres.  Blender is Z-up; the glTF exporter converts to Y-up.
* Models stand on the ground at the origin.  "Front" faces Blender -Y,
  which becomes +Z in three.js.
* Colours are written as FLOAT_COLOR face-corner attributes (linear).  The
  palette below is authored in sRGB and converted on write.
* Material slots (by name) tell the game how to shade a face:
    Mat_Base   - ordinary vertex-coloured surface
    Mat_Leaves - foliage; tinted by season and swayed by wind in-game
    Mat_Emit   - self-lit (flames, eyes, runes); feeds the bloom pass
    Mat_Metal  - slightly metallic / shiny
* Animated characters are hierarchies of rigid parts named body, head,
  arm_l, arm_r, leg_l, leg_r (+ optional extras) whose origins sit at the
  joints.  Sockets (hand_r, light, door, ...) are empties.
"""
