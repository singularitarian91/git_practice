def srgb_to_linear(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def col(name_or_rgb, mul=1.0):
    """Palette lookup (or pass-through tuple), optionally brightness-scaled."""
    rgb = P[name_or_rgb] if isinstance(name_or_rgb, str) else name_or_rgb
    return tuple(min(1.0, max(0.0, v * mul)) for v in rgb)


def mix(a, b, t):
    a = col(a)
    b = col(b)
    return tuple(a[i] * (1 - t) + b[i] * t for i in range(3))


